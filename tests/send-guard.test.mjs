import assert from 'node:assert/strict';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { createServer as createHttpServer } from 'node:http';
import { createServer } from 'vite';
import { JSDOM } from 'jsdom';

test('guard blocks native sending until hooks are ready, then permits it without double wrapping', async (t) => {
  const server = await createServer({ configFile: false, resolve: { alias: { '@': fileURLToPath(new URL('../src', import.meta.url)) } }, server: { middlewareMode: true, hmr: { server: createHttpServer() }, watch: null }, appType: 'custom' });
  t.after(() => server.close());
  const dom = new JSDOM('<body><div id="main"><footer><div role="textbox" contenteditable="true">你好</div><button aria-label="Send"><span data-icon="send"></span></button></footer></div></body>', { url: 'https://web.whatsapp.com' });
  t.after(() => { dom.window.dispatchEvent(new dom.window.Event('pagehide')); dom.window.close(); });
  for (const name of ['window', 'document', 'Node', 'Element', 'HTMLElement']) globalThis[name] = name === 'window' ? dom.window : dom.window[name];
  window.HTMLElement.prototype.getBoundingClientRect = () => ({ width: 100, height: 30 });
  const newsletter = { sendNewsletterTextMsg() {} };
  const modules = { WAWebNewsletterSendMsgAction: newsletter };
  window.require = (name) => modules[name];
  const { installSendGuard } = await server.ssrLoadModule('/src/page/send-guard.ts');
  installSendGuard();
  const editor = document.querySelector('[role="textbox"]');
  const button = document.querySelector('button');
  let nativeEvents = 0;
  button.addEventListener('click', () => nativeEvents++);
  editor.addEventListener('keydown', () => nativeEvents++);
  const click = () => button.querySelector('span').dispatchEvent(new window.MouseEvent('click', { bubbles: true, cancelable: true }));
  assert.equal(click(), false);
  assert.equal(editor.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true })), false);
  assert.equal(nativeEvents, 0);
  assert.match(document.querySelector('#wa-translate-send-notice').textContent, /尚未就绪/);
  modules.WAWebSendTextMsgChatAction = { sendTextMsgToChat() {} };
  assert.equal(click(), true);
  const wrapped = modules.WAWebSendTextMsgChatAction.sendTextMsgToChat;
  assert.equal(click(), true);
  assert.equal(modules.WAWebSendTextMsgChatAction.sendTextMsgToChat, wrapped);
  assert.equal(nativeEvents, 2);
  const replacement = () => {};
  modules.WAWebSendTextMsgChatAction.sendTextMsgToChat = replacement;
  assert.equal(click(), true);
  assert.notEqual(modules.WAWebSendTextMsgChatAction.sendTextMsgToChat, replacement);
  assert.equal(nativeEvents, 3);
  // A media preview created before its hook was installed must stay blocked.
  const preview = document.createElement('div');
  preview.innerHTML = '<div role="textbox" contenteditable="true">你好</div><button aria-label="Send"><span data-icon="send"></span></button>';
  document.body.append(preview);
  let mediaSent = false;
  preview.querySelector('button').addEventListener('click', () => { mediaSent = true; });
  assert.equal(preview.querySelector('span').dispatchEvent(new window.MouseEvent('click', { bubbles: true, cancelable: true })), false);
  assert.equal(mediaSent, false);
});
